"""Convert the paper tables (results/m13_tables.md) into LaTeX booktabs tables for main.tex.

    python paper/tables.py            (from the repository root; rerun after regenerating m13_tables.md)

Each ``## <title>`` section's first markdown table becomes ``paper/generated/<name>.tex`` (a ``tabular``
only; main.tex wraps it in a table float with its caption). Source tags such as ``[m9b]`` become small
superscripts, "pending" is set in italics, and "—" becomes an en dash. Standard library only.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# md section title prefix -> (output name, rotate the header cells: for many narrow numeric columns)
SECTIONS = {"Main table": ("main_table", True), "Ablation": ("ablation_table", False)}
# Short source tags and header names for print (the caption in main.tex gives the tag legend).
SHORT_TAGS = {"m12_demo": "dm", "m12_balance": "bl", "m12_connect": "cn", "diversity": "dv", "proposal": "pr",
              "brickgpt": "bg"}
SHORT_HEADERS = {"stable % (support rule)": "stable % (rule)", "stable % (physics, table)": "stands % (physics)",
                 "s per accepted design": "s / accepted design", "diversity: distinct designs %": "distinct designs %",
                 "diversity: normalized mean distance": "norm. mean distance"}
_TAG = re.compile(r"\s*\[([A-Za-z0-9_]+)\]")
_SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
            "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def escape(text: str) -> str:
    return "".join(_SPECIAL.get(ch, ch) for ch in text)


def cell(text: str) -> str:
    """One markdown cell as LaTeX: escaped, tags as superscripts, pending in italics, dashes, signs."""
    text = text.strip().replace("**", "")
    tags = _TAG.findall(text)
    body = _TAG.sub("", text).strip()
    if body in ("—", "-"):
        return "--"
    if body.lower() == "pending":
        out = r"\textit{pending}"
    else:
        out = escape(body).replace("—", "--").replace("≥", r"$\geq$").replace("≤", r"$\leq$")
        out = re.sub(r"^-(?=\d)", "$-$", out)  # a negative number, not a hyphen
        out = re.sub(r"(\d)e\+0?(\d+)$", r"\1$\\times 10^{\2}$", out)  # 1.19e+03
    return out + "".join(rf"\textsuperscript{{\,{escape(SHORT_TAGS.get(t, t))}}}" for t in tags)


def md_tables(text: str) -> dict[str, list[list[str]]]:
    """First table of each ``## `` section, as rows of cells (the separator row dropped)."""
    tables: dict[str, list[list[str]]] = {}
    section, finished = None, set()
    for line in text.splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
        elif section is None or section in finished:
            continue
        elif line.startswith("|"):
            cells = line.strip().strip("|").split("|")
            if not all(set(c.strip()) <= set("-: ") for c in cells):
                tables.setdefault(section, []).append(cells)
        elif section in tables:
            finished.add(section)  # only the section's first table
    return tables


def numeric(column: list[str]) -> bool:
    """Whether most filled cells of a column are numbers (right-aligned); "—" and "pending" do not count."""
    values = [_TAG.sub("", c).strip().replace("**", "") for c in column]
    values = [v for v in values if v not in ("—", "-", "") and v.lower() != "pending"]
    return bool(values) and sum(bool(re.match(r"^[-+]?\d", v)) for v in values) > len(values) / 2


def to_latex(rows: list[list[str]], rotate: bool) -> str:
    header, body = rows[0], rows[1:]
    spec = "l" + "".join("r" if numeric([r[i] for r in body]) else "l" for i in range(1, len(header)))
    header = [SHORT_HEADERS.get(h.strip(), h) for h in header]
    heads = [rf"\textbf{{{cell(h)}}}" if i == 0 or not rotate else rf"\rotatebox{{70}}{{{cell(h)}}}"
             for i, h in enumerate(header)]
    lines = [rf"\begin{{tabular}}{{{spec}}}", r"\toprule", " & ".join(heads) + r" \\", r"\midrule"]
    lines += [" & ".join(cell(c) for c in r) + r" \\" for r in body]
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def convert(source: Path, out_dir: Path) -> list[Path]:
    tables = md_tables(source.read_text(encoding="utf-8"))
    out_dir.mkdir(parents=True, exist_ok=True)
    label = source.relative_to(ROOT).as_posix() if source.is_relative_to(ROOT) else source.name
    written = []
    for title, rows in tables.items():
        found = next((v for prefix, v in SECTIONS.items() if title.startswith(prefix)), None)
        if found is None or not rows:
            continue
        name, rotate = found
        path = out_dir / f"{name}.tex"
        path.write_text(f"% Generated by paper/tables.py from {label}; do not edit.\n" + to_latex(rows, rotate),
                        encoding="utf-8")
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=ROOT / "results" / "m13_tables.md")
    parser.add_argument("--out", type=Path, default=ROOT / "paper" / "generated")
    args = parser.parse_args(argv)
    for path in convert(args.source, args.out):
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
